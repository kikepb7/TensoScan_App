package com.tensoscan.domain.measurement.repository

import com.tensoscan.domain.measurement.model.Measurement
import com.tensoscan.domain.measurement.model.MeasurementId
import kotlinx.coroutines.flow.Flow
import java.time.Duration
import java.time.Instant

/** Offline-first store of measurements: everything is written locally first and synchronised in the background. */
interface MeasurementRepository {
    /** The stored measurements, newest first, updated whenever they change. */
    fun observe(): Flow<List<Measurement>>

    suspend fun save(measurement: Measurement): Result<Unit>

    /** Measurements whose date lies within [window] of [around] (used to detect duplicates). */
    suspend fun findAround(around: Instant, window: Duration): Result<List<Measurement>>

    /**
     * Downloads the server's measurements and merges them into the local store. Measurements still waiting to be
     * uploaded (`PENDING`) or refused (`SYNC_FAILED`) are never touched.
     */
    suspend fun refresh(): Result<Unit>

    /**
     * Deletes a measurement. One that reached the server is removed there first and only then locally, so a failed
     * request leaves it visible instead of resurrecting it later.
     */
    suspend fun delete(id: MeasurementId): Result<Unit>

    /** Puts a refused measurement back in the queue (the user chose "retry"). */
    suspend fun markForRetry(id: MeasurementId): Result<Unit>

    /** Removes the local copy (when another user signs in or the account is deleted). */
    suspend fun clearLocal(): Result<Unit>

    /** Number of measurements that are not on the server yet. */
    fun observeUnsyncedCount(): Flow<Int>
}

/** Asks for the pending measurements to be uploaded when the network allows. */
fun interface MeasurementSyncScheduler {
    fun schedule()
}

/**
 * Keeps one account's measurements from being shown to another. The local store belongs to the account that last
 * signed in; when a different one signs in, whatever the previous account left behind is removed first.
 */
interface MeasurementOwnership {
    suspend fun claim(ownerKey: String)

    /** Forgets the owner (explicit sign-out, after the local data was removed). */
    suspend fun release()
}

/** A report saved on the device. [path] is opaque for the domain: only the layer that wrote it can open it. */
data class ReportFile(val path: String, val mimeType: String)

/** Downloads the PDF report generated by the server. Only available online. */
interface MeasurementReportRepository {
    /** The PDF with every measurement, with dates formatted in the time zone [timeZoneId] (IANA id). */
    suspend fun downloadPdf(timeZoneId: String): Result<ReportFile>
}
